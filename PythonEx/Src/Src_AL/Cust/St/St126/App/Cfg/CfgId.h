//=============================================================================
//  Configurations
//=============================================================================
// AL internal use
#define CFG_Develop                
// Macro for taking the build date generated by compiler
#define CFG_InfoDate       __DATE__
// Macro for taking the build time generated by compiler
#define CFG_InfoTime       __TIME__
// Info version
#define CFG_InfoVersion     JENKINS_SW_INFO_VERSION
// Software part no; for development not used, when this macro is changed also CFG_SOFT_EVOLUTION_INDEX shall be changed, and take care of CFG_SOFT_VERSION_PROJ7 and CFG_SOFT_EDITION_PROJ7
#define CFG_InfoPartNo      JENKINS_SW_INFO_PART_NUMBER

//=============================================================================
//  Section for CAN frame 0d7/0f7
//=============================================================================
// Increment for series SW delivery
#define CFG_SOFT_VERSION_PROJ7        JENKINS_SW_SERIES_VERSION
// Increment for sample SW delivery
#define CFG_SOFT_EDITION_PROJ7        JENKINS_SW_SAMPLE_VERSION
// Config system version has 0x01 as fixed value
#define CFG_SYSTEM_VERSION            0x01

//=============================================================================
//  Section for Authentification Zone
//=============================================================================
#define CFG_FUNCTPLANNB               JENKINS_FUNCTIONAL_PLAN_NUMBER // tbd-received from PSA
#define CFG_FUNCTPRODNB               JENKINS_FUNCTIONAL_PRODUCT_NUMBER // tbd-received from PSA
#define CFG_APPLI_TYPE                {0xFF, 0xFF, 0xFF, 0xFF}
#define CFG_SOFT_VERSION              0xFF      // 0xFF for flashable SW
#define CFG_SOFT_EDITION              0xFF      // 0xFF for flashable SW
// Soft evolution index; !!!!!!!!!!!shall be increased after each release after SOP!!!!!!!!!!!
#define CFG_SOFT_EVOLUTION_INDEX      JENKINS_SW_EVOLUTION_INDEX

//=============================================================================
//  Section for Log Zone
//=============================================================================
#define CFG_SW_BUILD_DAY              JENKINS_BUILD_DAY      // bcd
#define CFG_SW_BUILD_MONTH            JENKINS_BUILD_MONTH      // bcd
#define CFG_SW_BUILD_YEAR             JENKINS_BUILD_YEAR      // bcd

#define CFG_CALIBRATION_EDITION       0x01u

// The size of this structure is 36 decimal bytes = 0x24 hexadecimal bytes.
typedef struct structCfgId
{
  char strVersion[sizeof(CFG_InfoVersion)];     // 10+1=11 ASCII chars plus end of string terminator
  char strDate[sizeof(CFG_InfoDate)];           // 11+1=12 ASCII chars plus end of string terminator
  char strTime[sizeof(CFG_InfoTime)];
  char strPartNr[sizeof(CFG_InfoPartNo)];       // 12+1=13 ASCII chars plus end of string terminator
}
tCfgId;

