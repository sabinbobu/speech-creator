//-----------------------------------------------------------------------------
/// \brief  Pwm_GetFreq
///
/// \descr  get the frequency of the selected PWM channel
///
/// \param  ChannelNumber - handle of the PWM channel
/// \param  freq          - selected frequency in Hz
///
/// \return void
//-----------------------------------------------------------------------------
void Pwm_GetFreq(Pwm_ChannelType ChannelNumber, uint16* freq)
{
  uint8 ucIdx = 0u;

  for (ucIdx = 0u; ucIdx < UTIL_COUNTOF(pwm_channel_to_config_map_lut); ++ucIdx)
  {
    if (pwm_channel_to_config_map_lut[ucIdx].channel == ChannelNumber)
    {
      FTM_Type * ftmBase = g_ftmBase[pwm_channel_to_config_map_lut[ucIdx].instance_map_index];
      *freq = FTM_DRV_GetMod(ftmBase);
      pwm_config_instance_map_t* p = (pwm_config_instance_map_t*)&Pwm_Config.Pwm_Cfg_atyCharacteristics[0];
      // PRQA S 316 1 // Intended cast
      pwm_global_config_t* r = (pwm_global_config_t*)p->pwm_global_config;
      *freq -= (uint16)r[pwm_channel_to_config_map_lut[ucIdx].instance_map_index].pwmChannels[pwm_channel_to_config_map_lut[ucIdx].instance_map_index].counterInitialValue;
      break;
    }
  }
}

